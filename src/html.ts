/**
 * HTML escaping shared by every output path. It lives in its own module so the
 * page renderer and the Markdown renderer use one implementation.
 */
export function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}
